#!/usr/bin/env node
// Generates public/sw.js with an automatic content hash and complete precache asset list.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, posix } from "node:path";

const ROOT = new URL("..", import.meta.url).pathname;
const PUBLIC = join(ROOT, "public");
const OUT = join(PUBLIC, "sw.js");

const RUNTIME_DATA = new Set([
  "data/levels.json",
  "data/exercises.json",
  "data/tests.json",
  "data/decision-config.json",
  "data/profile.json",
  "data/posture-cycle.json",
]);

function walk(dir) {
  const out = [];
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, ent.name);
    if (ent.isDirectory()) {
      if (ent.name === "__") continue;
      out.push(...walk(full));
    } else {
      out.push(full);
    }
  }
  return out;
}

const files = walk(PUBLIC)
  .map((f) => relative(PUBLIC, f).split("\\").join("/"))
  .filter((rel) => {
    if (rel === "sw.js" || rel === "index.html") return false;
    if (rel.startsWith("data/")) return RUNTIME_DATA.has(rel);
    return rel === "styles.css" || rel === "app.js" || rel === "manifest.webmanifest"
      || rel.startsWith("js/") || rel.startsWith("icons/");
  })
  .sort();

const hash = createHash("sha256");
for (const rel of ["index.html", ...files]) {
  hash.update(rel).update("\0").update(readFileSync(join(PUBLIC, rel))).update("\0");
}
const version = hash.digest("hex").slice(0, 10);
const assets = ["./", ...files];

const sw = `// Generated by scripts/gen-sw.mjs — do not edit by hand.
// Cloudflare 307-redirects /index.html to /, so only "./" is precached (offline navigations fall back to it).
const CACHE = "pt-${version}";
// Firebase SDK modules from the gstatic CDN (versioned, immutable URLs): cached on first use so a
// signed-in device still starts offline. Kept across app-cache bumps.
const SDK_CACHE = "pt-firebase-sdk";
const ASSETS = [
${assets.map((a) => `  ${JSON.stringify(a)},`).join("\n")}
];

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE && k !== SDK_CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});
// Cache first (instant + fully offline), refreshing the cache in the background.
self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin === "https://www.gstatic.com" && url.pathname.startsWith("/firebasejs/")) {
    event.respondWith(
      caches.open(SDK_CACHE).then((c) =>
        c.match(req).then((hit) => hit || fetch(req).then((res) => { if (res.ok) c.put(req, res.clone()); return res; }))
      )
    );
    return;
  }
  // Same-origin only. /__/ is Firebase Auth's self-hosted sign-in helper: always straight to the network.
  if (url.origin !== self.location.origin || url.pathname.startsWith("/__/")) return;
  event.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      const net = fetch(req)
        .then((res) => {
          if (res.ok && res.type === "basic" && !res.redirected) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => hit || (req.mode === "navigate" ? caches.match("./") : undefined));
      return hit || net;
    })
  );
});

// Tapping a timer notification brings the open PT tab (or a new one) to the front on the Work screen.
self.addEventListener("notificationclick", (event) => {
  event.notification.close();
  event.waitUntil(
    self.clients.matchAll({ type: "window", includeUncontrolled: true }).then((list) => {
      const open = list.find((c) => new URL(c.url).origin === self.location.origin);
      if (open) {
        if (open.navigate) open.navigate(new URL("./#/work", self.registration.scope).href).catch(() => {});
        return open.focus();
      }
      return self.clients.openWindow("./#/work");
    })
  );
});
`;

writeFileSync(OUT, sw);
console.log(`Generated public/sw.js (CACHE = pt-${version}, ${assets.length} assets)`);
